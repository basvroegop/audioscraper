const { chromium } = require('@playwright/test');
const origin = process.env.AUDIOSCRAPER_ORIGIN || 'http://127.0.0.1:8788';
const out = process.env.OUT_DIR || '/app/test-results';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(origin);
 await page.getByRole('heading',{name:'Je projecten'}).waitFor();
 await page.locator('.project-card').first().waitFor();
 await page.screenshot({path:out+'/dashboard-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Nieuw project',exact:false}).first().click();
 await page.getByLabel('Bron-URL').fill('http://127.0.0.1/feed');
 await page.getByRole('button',{name:'Project aanmaken',exact:false}).click();
 await page.locator('#form-error').filter({hasText:'openbare'}).waitFor();
 await page.getByRole('button',{name:'Sluiten',exact:true}).click();
 await page.locator('.project-card a.project-open').first().click();
 await page.getByRole('heading',{name:'Overzicht',exact:true}).waitFor();
 await page.locator('.episode-card').first().click();
 await page.getByRole('heading',{name:'Volledig transcript',exact:true}).waitFor();
 await page.screenshot({path:out+'/detail-desktop.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.goto(origin+'/#library');
 await page.getByRole('heading',{name:'Bibliotheek',exact:true}).waitFor();
 await page.screenshot({path:out+'/dashboard-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Mobile horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('Browser checks passed: project hub, project environment, transcript, combined library, mobile, add-project validation; no JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
