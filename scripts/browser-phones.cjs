const {chromium, expect} = require('@playwright/test');
(async()=>{
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(String(error)));
  const origin=process.env.AUDIOSCRAPER_ORIGIN||'http://127.0.0.1:8788';
  const phones=await (await page.request.get(origin+'/api/phone-numbers')).json();
  const linked=phones.filter(phone=>phone.company);
  const confirmed=phones.filter(phone=>phone.company||phone.attribution?.state==='confirmed');
  await page.goto(origin+'/#entities');
  await page.getByRole('heading',{name:/^Telefoonnummers/}).waitFor();
  await expect(page.locator('.phone-row')).toHaveCount(phones.length);
  await expect(page.getByText(`${confirmed.length} bevestigd`,{exact:false})).toBeVisible();
  await expect(page.locator('.phone-lookup-status').first()).toBeVisible();
  await page.getByLabel('Beoordeling',{exact:true}).selectOption('mobile');
  await expect(page).toHaveURL(/status=mobile/);
  const mobileCount=phones.filter(phone=>phone.category==='Mobiel nummer'&&!phone.company).length;
  await expect(page.locator('.phone-row')).toHaveCount(mobileCount);
  await page.getByLabel('Beoordeling',{exact:true}).selectOption('');
  const verified=page.locator('.phone-row').filter({hasText:'Studio Perfect'});
  await expect(verified.locator('.phone-company')).toContainText('Ceintuurbaan');
  await expect(verified.locator('.phone-company a').first()).toHaveAttribute('href',/studioperfect\.nl/);
  await page.screenshot({path:'/app/test-results/phone-lookup-desktop.png'});
  await page.getByLabel('Regio',{exact:true}).selectOption('north');
  await expect(page).toHaveURL(/entities\?region=north$/);
  await expect(page.locator('.phone-row').filter({hasText:'Dovida Friesland'})).toBeVisible();
  await expect(page.locator('.phone-row').filter({hasText:'Energie Service Friesland'})).toBeVisible();
  await expect(page.locator('.phone-row').filter({hasText:'Studio Perfect'})).toHaveCount(0);
  await expect(page.locator('[data-phone="0523648635"]')).toHaveCount(0);
  await page.getByRole('heading',{name:/^Telefoonnummers/}).click();
  await page.waitForTimeout(6500);
  await expect(page.getByLabel('Regio',{exact:true})).toHaveValue('north');
  await page.reload();
  await expect(page.getByLabel('Regio',{exact:true})).toHaveValue('north');
  await expect(page.locator('.phone-row').filter({hasText:'Energie Service Friesland'})).toBeVisible();
  await page.screenshot({path:'/app/test-results/phone-regions-desktop.png'});
  await page.getByLabel('Regio',{exact:true}).selectOption('Groningen');
  await expect(page.locator('.phone-row').filter({hasText:'Dovida Friesland'})).toHaveCount(0);
  await page.getByLabel('Regio',{exact:true}).selectOption('Friesland');
  await expect(page.locator('.phone-row').filter({hasText:'Dovida Friesland'})).toBeVisible();
  await page.getByLabel('Regio',{exact:true}).selectOption('');
  await expect(verified).toBeVisible();
  await verified.locator('.phone-context').first().click();
  await expect(page).toHaveURL(/episode\/[^?]+\?segment=\d+/);
  await expect(page.locator('.segment.target')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.goto(origin+'/#entities?region=north');
  await page.getByRole('heading',{name:/^Telefoonnummers/}).waitFor();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)){
    const offenders=await page.locator('body *').evaluateAll(elements=>elements.map(element=>({tag:element.tagName,class:element.className,width:element.scrollWidth,right:element.getBoundingClientRect().right})).filter(item=>item.width>innerWidth||item.right>innerWidth+1).slice(0,12));
    throw Error('Mobile horizontal overflow: '+JSON.stringify(offenders));
  }
  await page.screenshot({path:'/app/test-results/phone-lookup-mobile.png'});
  if(errors.length)throw Error(errors.join('\n'));
  console.log(JSON.stringify({result:'passed',numbers:phones.length,linked:linked.length,checks:['lookup and context status','review filter','counts','source and location','north and province filters','0800 company location','outside company excluded','filter persists through refresh','transcript deep link','mobile layout','no JS errors']}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
